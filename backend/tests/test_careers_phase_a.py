def test_status_transition_and_history():
    """30 canonical statuses accepted; invalid rejected; history logged."""
    job = _make_job()
    email = f"phaseA_hist_{int(time.time())}@test.com"
    app_id = _apply(job["job_id"], email).json()["application_id"]

    # 10 sequential transitions
    for status in [
        "under_screening", "shortlisted", "test_assigned", "test_completed",
        "hr_interview_scheduled", "selected", "documents_verified",
        "offer_generated", "offer_accepted", "joined",
    ]:
        r = requests.put(
            f"{API}/api/public/careers/applications/{app_id}/status",
            json={"status": status, "admin_id": "pytest", "comment": f"→{status}"},
            timeout=30,
        )
        assert r.status_code == 200, r.text
        assert r.json()["status"] == status

    # Invalid status rejected
    r = requests.put(
        f"{API}/api/public/careers/applications/{app_id}/status",
        json={"status": "bogus"},
        timeout=30,
    )
    assert r.status_code == 400
    assert "Invalid status" in r.json()["detail"]

    # History has all 10 transitions plus the initial system entry
    rl = requests.get(f"{API}/api/public/careers/applications", timeout=30).json()
    app = next(a for a in rl["applications"] if a["application_id"] == app_id)
    hist = app.get("status_history", [])
    assert len(hist) >= 11
    assert hist[0]["from"] is None and hist[0]["to"] == "application_received"
    assert hist[-1]["to"] == "joined"


