def test_job_lifecycle_actions_and_public_visibility():
    """Spec §55: pause hides from public listing; reopen restores."""
    job = _make_job()
    # Confirm it is publicly visible while published
    listing = requests.get(f"{API}/api/public/careers/jobs?active_only=true", timeout=30).json()["jobs"]
    assert any(j["job_id"] == job["job_id"] for j in listing)

    # Pause → gone from public listing
    r = requests.post(
        f"{API}/api/public/careers/jobs/{job['job_id']}/lifecycle",
        json={"action": "pause"}, timeout=30,
    )
    assert r.status_code == 200 and r.json()["job_status"] == "paused"
    listing = requests.get(f"{API}/api/public/careers/jobs?active_only=true", timeout=30).json()["jobs"]
    assert not any(j["job_id"] == job["job_id"] for j in listing)

    # Reopen → visible again
    r = requests.post(
        f"{API}/api/public/careers/jobs/{job['job_id']}/lifecycle",
        json={"action": "reopen"}, timeout=30,
    )
    assert r.status_code == 200 and r.json()["job_status"] == "published"

    # Invalid action → 400
    r = requests.post(
        f"{API}/api/public/careers/jobs/{job['job_id']}/lifecycle",
        json={"action": "explode"}, timeout=30,
    )
    assert r.status_code == 400


def test_paused_job_rejects_new_applications():
    job = _make_job()
    requests.post(
        f"{API}/api/public/careers/jobs/{job['job_id']}/lifecycle",
        json={"action": "pause"}, timeout=30,
    )
    r = _apply(job["job_id"], f"phaseA_paused_{int(time.time())}@test.com")
    assert r.status_code == 400
    assert "no longer accepting" in r.json()["detail"].lower() or "paused" in r.json()["detail"].lower()


def test_duplicate_job_creates_draft_with_new_code():
    """Spec §55: duplicated job gets a fresh draft with distinct job_code."""
    job = _make_job()
