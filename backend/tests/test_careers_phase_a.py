def test_auto_close_when_vacancies_filled():
    """Spec §55 auto_close_when_filled + §56 vacancy tracking."""
    job = _make_job(vacancy_count=1, auto_close_when_filled=True)
    email = f"phaseA_close_{int(time.time())}@test.com"
    app_id = _apply(job["job_id"], email).json()["application_id"]
    # Drive the applicant through to `joined`
    for status in ["shortlisted", "selected", "joined"]:
        r = requests.put(
            f"{API}/api/public/careers/applications/{app_id}/status",
            json={"status": status, "admin_id": "pytest"}, timeout=30,
        )
        assert r.status_code == 200
    # Job should be closed automatically
    detail = requests.get(f"{API}/api/public/careers/jobs/{job['job_id']}", timeout=30).json()["job"]
    assert detail["job_status"] == "closed"
    # New applications now blocked
    r = _apply(job["job_id"], f"phaseA_after_close_{int(time.time())}@test.com")
    assert r.status_code == 400
