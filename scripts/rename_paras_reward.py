"""
One-shot find-and-replace: PARAS REWARD → PARAS REWARDS everywhere in
source files.  Adds a trailing "S" to the brand name.

Handled cases (all three casings):
  • PARAS REWARD  → PARAS REWARDS
  • Paras Reward  → Paras Rewards
  • paras reward  → paras rewards
    (only the space-separated brand form — never touches identifiers,
    URLs, emails, package names, DB names, etc.)

Skipped:
  • URLs/domains: parasreward.com, parasreward.in (no space, unaffected
    by our space-form regex).
  • Emails: info@parasreward.com etc — same reason.
  • Compiled Android JS bundles (android/app/src/main/assets/public/).
  • node_modules, .git, __pycache__, test_reports, build artefacts.

Idempotent — running twice does not double-append (negative lookahead on
trailing s/S).
"""

import os
import re
from pathlib import Path


ROOT = Path("/app")

# Only edit source files inside these roots
INCLUDE_ROOTS = [
    ROOT / "frontend" / "src",
    ROOT / "frontend" / "public",
    ROOT / "frontend" / "android" / "app" / "src" / "main" / "res",
    ROOT / "frontend" / "android" / "app" / "src" / "main" / "AndroidManifest.xml",
    ROOT / "frontend" / "android" / "app" / "build.gradle",
    ROOT / "backend",
]

# Fine-grained skip list
SKIP_DIRS = {
    "node_modules", ".git", "__pycache__", "test_reports", ".venv",
    "build", "dist", "coverage",
    # Compiled JS bundles (get regenerated by yarn build)
    "assets",
}

# Extensions we actually touch. Anything else is left alone.
INCLUDE_EXTS = {
    ".js", ".jsx", ".ts", ".tsx", ".html", ".css",
    ".py", ".json", ".md", ".xml", ".gradle", ".kt", ".java",
    ".txt", ".yml", ".yaml", ".properties",
}

# The three brand-form regexes.  Word boundaries + negative lookahead
# make the operation idempotent (already-plural form is left untouched).
PATTERNS = [
    (re.compile(r"\bPARAS REWARD\b(?![sS])"), "PARAS REWARDS"),
    (re.compile(r"\bParas Reward\b(?![sS])"), "Paras Rewards"),
    (re.compile(r"\bparas reward\b(?![sS])"), "paras rewards"),
]


def should_skip_path(p: Path) -> bool:
    parts = set(p.parts)
    return bool(parts & SKIP_DIRS)


def iter_files():
    for base in INCLUDE_ROOTS:
        if not base.exists():
            continue
        if base.is_file():
            yield base
            continue
        for root, dirs, files in os.walk(base):
            # Prune skip dirs in-place
            dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
            for f in files:
                fp = Path(root) / f
                if fp.suffix.lower() in INCLUDE_EXTS:
                    yield fp


def process_file(path: Path) -> int:
    """Return number of replacements applied to this file."""
    try:
        original = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return 0

    updated = original
    n_total = 0
    for pattern, replacement in PATTERNS:
        updated, n = pattern.subn(replacement, updated)
        n_total += n

    if n_total > 0 and updated != original:
        path.write_text(updated, encoding="utf-8")
    return n_total


def main():
    total_files = 0
    total_hits = 0
    touched = []
    for fp in iter_files():
        if should_skip_path(fp):
            continue
        n = process_file(fp)
        if n:
            total_hits += n
            total_files += 1
            touched.append((str(fp), n))

    touched.sort(key=lambda x: -x[1])
    print(f"\n=== SUMMARY ===")
    print(f"Files modified : {total_files}")
    print(f"Total replaces : {total_hits}")
    print(f"\nTop 20 files by count:")
    for fp, n in touched[:20]:
        print(f"  {n:5d}  {fp}")


if __name__ == "__main__":
    main()
